/**
 * Central footer configuration.
 *
 * Every footer entry has an explicit, meaningful action:
 *  - `route`  → an existing app route
 *  - `modal`  → an informational modal whose content lives in FOOTER_INFO_MODALS
 *  - `tel` / `mailto` → direct contact links
 * No link may point to "#" — every entry must have a purpose.
 */

export type FooterAction =
  | { type: "route"; href: string }
  | { type: "modal"; modalId: string }
  | { type: "tel"; href: string }
  | { type: "mailto"; href: string };

export interface FooterLink {
  label: string;
  action: FooterAction;
}

export interface FooterColumn {
  title: string;
  links: FooterLink[];
}

export interface FooterSocial {
  id: string;
  label: string;
  icon: string;
  action: FooterAction;
}

